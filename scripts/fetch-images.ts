// Run from the repo root (npm run images:fetch).
const ROOT = process.cwd();
const IMAGES_DIR = path.join(ROOT, 'assets', 'images');
const MANIFEST = path.join(IMAGES_DIR, 'manifest.json');
const REGISTRY = path.join(ROOT, 'src', 'features', 'images.ts');
const ATTRIBUTION = path.join(ROOT, 'ATTRIBUTION.md');

export const fileFor = (e: Pick<Entry, 'kind' | 'key'>) =>
  path.join(IMAGES_DIR, e.kind, `${e.key}.jpg`);

/** Source of src/features/images.ts for the files that exist. */
export function renderRegistry(present: Pick<Entry, 'kind' | 'key'>[]): string {
  const block = (kind: Kind) =>
    present
      .filter((e) => e.kind === kind)
      .sort((a, b) => a.key.localeCompare(b.key))
      .map((e) => `  ${e.key}: require('../../assets/images/${kind}/${e.key}.jpg'),`)
      .join('\n');
  return `// Generated by scripts/fetch-images.ts — do not edit by hand.
/**
 * Bundled photos keyed by imageKey (recipes: "z1"…, ingredients: ingredient id).
 * Missing keys fall back to an icon.
 */
export const RECIPE_IMAGES: Readonly<Record<string, number>> = {
${block('recipes')}
};
export const INGREDIENT_IMAGES: Readonly<Record<string, number>> = {
${block('ingredients')}
};
`;
}

export function renderAttribution(credits: Credit[]): string {
  const rows = [...credits]
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.key.localeCompare(b.key))
    .map(
      (c) =>
        `| ${c.kind}/${c.key}.jpg | [${c.photographer}](${c.photographerUrl}) | [Pexels](${c.pageUrl}) |`,
    );
  return [
    '# Photo attribution',
    '',
    'Photos by [Pexels](https://www.pexels.com) contributors, used under the [Pexels License](https://www.pexels.com/license/).',
    '',
    '| File | Photographer | Source |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

type PexelsPhoto = {
  url: string;
  photographer: string;
  photographer_url: string;
  src: { large: string; medium: string };
};

async function search(apiKey: string, query: string, pick = 0): Promise<PexelsPhoto | undefined> {
  const url = `https://api.pexels.com/v1/search?${new URLSearchParams({ query, per_page: '5', orientation: 'landscape' })}`;
  const res = await fetch(url, { headers: { Authorization: apiKey } });
  if (res.status === 401) throw new Error('Pexels rejected the API key (401)');
  if (res.status === 429) throw new Error('Pexels rate limit reached (429) — try again later');
  if (!res.ok) throw new Error(`Pexels search failed: ${res.status}`);
  const body = (await res.json()) as { photos?: PexelsPhoto[] };
  return body.photos?.[pick] ?? body.photos?.[0];
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function main() {
  const argv = process.argv.slice(2);
  const args = new Set(argv);
  const only = new Set(
    argv
      .find((a) => a.startsWith('--only='))
      ?.slice('--only='.length)
      .split(',')
      .filter(Boolean) ?? [],
  );
  // --only=z3,oil re-downloads just those keys.
  const force = args.has('--force') || only.size > 0;
  const dryRun = args.has('--dry-run');

  if (dryRun) {
    for (const e of IMAGE_QUERIES)
      console.log(`${existsSync(fileFor(e)) ? '✓' : '·'} ${e.kind}/${e.key}: "${e.query}"`);
    return;
  }

  const apiKey = process.env.PEXELS_API_KEY;
  if (!apiKey || apiKey === '<PEXELS_API_KEY>') {
    console.error(
      'PEXELS_API_KEY is missing. Put PEXELS_API_KEY=<your key> into .env.local (gitignored).',
    );
    process.exitCode = 1;
    return;
  }

  const credits: Credit[] = existsSync(MANIFEST)
    ? (JSON.parse(readFileSync(MANIFEST, 'utf8')) as Credit[])
    : [];
  const byFile = new Map(credits.map((c) => [`${c.kind}/${c.key}`, c]));

  for (const e of IMAGE_QUERIES) {
    const target = fileFor(e);
    if (only.size > 0 && !only.has(e.key)) continue;
    if (!force && existsSync(target)) continue;
    const photo = await search(apiKey, e.query, e.pick);
    if (!photo) {
      console.warn(`No photo for ${e.kind}/${e.key} ("${e.query}")`);
      continue;
    }
    const image = await fetch(e.kind === 'recipes' ? photo.src.large : photo.src.medium);
    if (!image.ok) throw new Error(`Download failed for ${e.key}: ${image.status}`);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, Buffer.from(await image.arrayBuffer()));
    byFile.set(`${e.kind}/${e.key}`, {
      key: e.key,
      kind: e.kind,
      photographer: photo.photographer,
      photographerUrl: photo.photographer_url,
      pageUrl: photo.url,
    });
    console.log(`✓ ${e.kind}/${e.key} — ${photo.photographer}`);
    await sleep(400); // stay far below the 200 requests/hour limit
  }

  const present = IMAGE_QUERIES.filter((e) => existsSync(fileFor(e)));
  const kept = [...byFile.values()].filter((c) =>
    present.some((p) => p.kind === c.kind && p.key === c.key),
  );
  writeFileSync(MANIFEST, `${JSON.stringify(kept, null, 2)}\n`);
  writeFileSync(ATTRIBUTION, renderAttribution(kept));
  writeFileSync(REGISTRY, renderRegistry(present));
  console.log(`Done: ${present.length}/${IMAGE_QUERIES.length} images. Rebuild or reload the app.`);
}

if (process.argv[1]?.endsWith('fetch-images.ts')) {
  main().catch((e: unknown) => {
    console.error(e instanceof Error ? e.message : e);
    process.exitCode = 1;
  });
}
