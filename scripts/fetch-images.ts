/**
 * Downloads dish and product photos from Pexels once, into the app bundle.
 *
 *   PEXELS_API_KEY=<PEXELS_API_KEY> in .env.local (gitignored), then:
 *   npm run images:fetch            # skips files that already exist
 *   npm run images:fetch -- --force # re-download everything
 *   npm run images:fetch -- --only=z3,oil  # re-download selected keys
 *   npm run images:fetch -- --dry-run
 *
 * Writes assets/images/{recipes,ingredients}/<key>.jpg, assets/images/manifest.json,
 * ATTRIBUTION.md and regenerates src/features/images.ts. Pexels photos are free to use;
 * attribution is kept anyway (https://www.pexels.com/license/).
 */
