/**
 * images — photos for the catalog (PHASE_2 task 5):
 * - recipes: TheMealDB photo of every accepted recipe → WebP, long side 800 px;
 * - products: Pexels search for every shipped product without a v1 photo → WebP 400 px;
 *   staples (spices, salt…) keep the category placeholder on purpose.
 * Downloads are cached in raw/images/; output goes to the app's assets/images/catalog/.
 * Credits are written to assets/images/catalog/credits.json for the attribution page.
 */
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import sharp from 'sharp';

import { config } from '../pipeline.config.ts';
import type { Accepted } from './build/evaluate.ts';
import { loadMappings } from './build/mappings.ts';
import { loadOwnRecipes } from './own/recipes.ts';
import { get, sleep } from './lib/http.ts';
import { APP_ROOT, ensureDir, MAPPINGS, RAW, REPORTS, ROOT } from './lib/paths.ts';

export type Credit = {
  file: string;
  source: 'TheMealDB' | 'Pexels';
  author: string | null;
  authorUrl: string | null;
  pageUrl: string;
};

/** What the raw cache keeps next to a Pexels photo: its credit and the query that found it. */
type Sidecar = Credit & { query?: string };

/** mappings/photo-review.json: per product, `ok`, `reject` (placeholder) or a new query. */
type PhotoReview = Record<string, 'ok' | 'reject' | { query: string; ok?: boolean }>;

function readPhotoReview(): PhotoReview {
  const file = path.join(MAPPINGS, 'photo-review.json');
  return existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as PhotoReview) : {};
}

/** A page with the photos awaiting review, opened from reports/ in a browser. */
function reviewPage(items: readonly { id: string; query: string; raw: string; credit: Credit }[]) {
  const cards = items
    .map(
      (i) =>
        `<figure><img src="${path.relative(REPORTS, i.raw)}" loading="lazy"><figcaption><b>${i.id}</b><br>«${i.query}»</figcaption></figure>`,
    )
    .join('\n');
  return `<!doctype html><meta charset="utf-8"><title>Product photos to review</title>
<style>body{font:14px system-ui;margin:16px}main{display:grid;grid-template-columns:repeat(auto-fill,minmax(160px,1fr));gap:12px}
img{width:100%;aspect-ratio:1;object-fit:cover;border-radius:8px}figure{margin:0}</style>
<h1>${items.length} photos awaiting review</h1>
<p>Mark each id in mappings/photo-review.json: "ok", "reject", or {"query": "…"} to search again ({"query": "…", "ok": true} once it is right).</p>
<main>${cards}</main>`;
}

const OUT = path.join(APP_ROOT, 'assets', 'images', 'catalog');
const V1_PHOTOS = path.join(APP_ROOT, 'assets', 'images', 'ingredients');
const CREDITS = path.join(OUT, 'credits.json');
const ATTRIBUTION = path.join(APP_ROOT, 'assets', 'ATTRIBUTION.md');

function attribution(credits: readonly Credit[]): string {
  const pexels = credits.filter((c) => c.source === 'Pexels');
  const recipes = credits.filter((c) => c.source === 'TheMealDB').length;
  return [
    '# Attribution',
    '',
    'Generated by `tools/data-pipeline` (`npm run images`). Do not edit by hand.',
    '',
    '## Data',
    '',
    '- **TheMealDB** (https://www.themealdb.com) — recipes and dish photos ' +
      `(${recipes} photos in \`assets/images/catalog/recipes/\`). Texts translated and split into steps.`,
    '- **USDA FoodData Central** (https://fdc.nal.usda.gov) — nutrition per 100 g. Public domain (CC0 1.0).',
    '- **Open Food Facts** (https://world.openfoodfacts.org) — store products. Database: Open Database ' +
      'License (ODbL) 1.0; product photos: Creative Commons Attribution-ShareAlike (CC BY-SA).',
    '- **Pexels** (https://www.pexels.com) — product photos under the Pexels License.',
    '',
    'Photos of the original recipes and products (v1) are credited in the repository root `ATTRIBUTION.md`.',
    '',
    '## Product photos (Pexels)',
    '',
    '| File | Photographer | Source |',
    '|---|---|---|',
    ...pexels.map(
      (c) =>
        `| ${c.file} | ${c.author && c.authorUrl ? `[${c.author}](${c.authorUrl})` : (c.author ?? '—')} | ${c.pageUrl} |`,
    ),
    '',
  ].join('\n');
}

async function toWebp(input: string, output: string, maxSide: number): Promise<void> {
  ensureDir(path.dirname(output));
  await sharp(input)
    .rotate()
    .resize({ width: maxSide, height: maxSide, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: config.images.quality })
    .toFile(output);
}

async function download(url: string, file: string, overwrite = false): Promise<boolean> {
  if (existsSync(file) && !overwrite) return false;
  const res = await get(url, 'image/*');
  ensureDir(path.dirname(file));
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  return true;
}

type PexelsPhoto = {
  url: string;
  photographer: string;
  photographer_url: string;
  src: { medium: string; large: string };
};

async function pexels(query: string, apiKey: string): Promise<PexelsPhoto | undefined> {
  const url = `https://api.pexels.com/v1/search?${new URLSearchParams({
    query,
    per_page: '3',
    orientation: 'square',
  })}`;
  const res = await fetch(url, { headers: { Authorization: apiKey } });
  if (res.status === 429)
    throw new Error('Pexels rate limit (429): run again later, progress is cached');
  if (!res.ok) throw new Error(`Pexels search failed: ${res.status}`);
  return ((await res.json()) as { photos?: PexelsPhoto[] }).photos?.[0];
}

async function main() {
  const accepted = JSON.parse(
    readFileSync(path.join(ROOT, 'cache', 'evaluated.json'), 'utf8'),
  ) as Accepted[];
  const { canonical } = loadMappings();
  const credits = new Map<string, Credit>(
    existsSync(CREDITS)
      ? (JSON.parse(readFileSync(CREDITS, 'utf8')) as Credit[]).map((c) => [c.file, c])
      : [],
  );

  // ---------- recipes ----------
  let recipeFetches = 0;
  for (const r of accepted) {
    if (!r.thumb) continue;
    const raw = path.join(RAW, 'images', 'mealdb', `${r.sourceId}.jpg`);
    if (await download(r.thumb, raw)) {
      recipeFetches++;
      await sleep(config.mealdb.pauseMs);
    }
    const file = `recipes/${r.id}.webp`;
    if (!existsSync(path.join(OUT, file)))
      await toWebp(raw, path.join(OUT, file), config.images.recipeSide);
    credits.set(file, {
      file,
      source: 'TheMealDB',
      author: null,
      authorUrl: null,
      pageUrl: `https://www.themealdb.com/meal/${r.sourceId}`,
    });
  }

  // Recipes that left the catalog: drop their photo and credit.
  const recipeFiles = new Set(
    [...accepted.map((r) => r.id), ...loadOwnRecipes().map((r) => r.id)].map(
      (id) => `recipes/${id}.webp`,
    ),
  );
  for (const file of [...credits.keys()]) {
    if (file.startsWith('recipes/') && !recipeFiles.has(file)) {
      rmSync(path.join(OUT, file), { force: true });
      credits.delete(file);
    }
  }

  // ---------- products ----------
  // Only photos a person approved in mappings/photo-review.json ship; keyword search picks
  // wrong pictures often (live chickens for «chicken stock»), the rest keep the placeholder.
  const review = readPhotoReview();
  const v1 = new Set(readdirSync(V1_PHOTOS).map((f) => f.replace(/\.\w+$/, '')));
  const used = new Set(accepted.flatMap((r) => r.lines.map((l) => l.ingredientId)));
  const shipped = canonical.filter((p) => used.has(p.id) || v1.has(p.id));
  const wanted = shipped.filter((p) => !v1.has(p.id) && !p.isStaple);
  const apiKey = process.env.PEXELS_API_KEY;
  let searches = 0;
  const notFound: string[] = [];
  const pending: { id: string; query: string; raw: string; credit: Credit }[] = [];
  const counts = { approved: 0, rejected: 0, pending: 0 };
  // Own recipes (breakfasts and snacks) have no TheMealDB photo: reviewed Pexels photos too.
  const targets = [
    ...wanted.map((p) => ({
      key: p.id,
      file: `products/${p.id}.webp`,
      defaultQuery: `${p.nameEn} food`,
      maxSide: config.images.productSide,
      large: false,
    })),
    ...loadOwnRecipes().map((r) => ({
      key: r.id,
      file: `recipes/${r.id}.webp`,
      defaultQuery: r.nameEn,
      maxSide: config.images.recipeSide,
      large: true,
    })),
  ];
  for (const target of targets) {
    const { key, file, defaultQuery } = target;
    const out = path.join(OUT, file);
    const raw = path.join(RAW, 'images', 'pexels', `${key}.jpg`);
    const sidecar = raw.replace(/\.jpg$/, '.json');
    const entry = review[key];
    const unship = () => {
      rmSync(out, { force: true });
      credits.delete(file);
    };
    if (entry === 'reject') {
      counts.rejected++;
      unship();
      continue;
    }
    const query = typeof entry === 'object' ? entry.query : defaultQuery;

    let side = existsSync(sidecar)
      ? (JSON.parse(readFileSync(sidecar, 'utf8')) as Sidecar)
      : credits.has(file)
        ? { ...credits.get(file)!, query: defaultQuery } // photos from older runs
        : undefined;
    if (side && (side.query ?? defaultQuery) !== query) {
      // A new query for this product: forget the old photo.
      for (const f of [raw, sidecar]) rmSync(f, { force: true });
      unship();
      side = undefined;
    }
    if (!side || !existsSync(raw)) {
      if (!apiKey) {
        notFound.push(key);
        continue;
      }
      const photo = await pexels(query, apiKey);
      searches++;
      await sleep(config.images.pexelsPauseMs);
      if (!photo) {
        notFound.push(key);
        unship();
        continue;
      }
      side = {
        file,
        source: 'Pexels',
        author: photo.photographer,
        authorUrl: photo.photographer_url,
        pageUrl: photo.url,
        query,
      };
      await download(target.large ? photo.src.large : photo.src.medium, raw, true);
    }
    // The credit sits next to the raw photo so an interrupted run does not lose it.
    ensureDir(path.dirname(sidecar));
    writeFileSync(sidecar, JSON.stringify(side));
    const { query: _query, ...credit } = side;

    const approved = entry === 'ok' || (typeof entry === 'object' && entry.ok === true);
    if (!approved) {
      counts.pending++;
      pending.push({ id: key, query, raw, credit });
      unship();
      continue;
    }
    counts.approved++;
    credits.set(file, credit);
    if (!existsSync(out)) await toWebp(raw, out, target.maxSide);
  }
  writeFileSync(path.join(REPORTS, 'product-photos.html'), reviewPage(pending));

  ensureDir(OUT);
  const sorted = [...credits.values()].sort((a, b) => a.file.localeCompare(b.file));
  writeFileSync(CREDITS, JSON.stringify(sorted, null, 1));
  writeFileSync(ATTRIBUTION, attribution(sorted));

  const size = (dir: string) =>
    existsSync(dir)
      ? readdirSync(dir).reduce((s, f) => s + statSync(path.join(dir, f)).size, 0)
      : 0;
  const mb = (b: number) => (b / 1024 / 1024).toFixed(1);
  console.log(
    `images: recipes ${accepted.length} (${recipeFetches} downloaded, ${mb(size(path.join(OUT, 'recipes')))} MB), ` +
      `products: ${counts.approved} approved, ${counts.rejected} rejected, ${counts.pending} awaiting review ` +
      `of ${wanted.length} (${searches} Pexels searches, ${mb(size(path.join(OUT, 'products')))} MB), ` +
      `staples on placeholder: ${shipped.filter((p) => p.isStaple && !v1.has(p.id)).length}` +
      (notFound.length ? `, nothing found: ${notFound.join(', ')}` : ''),
  );
}

await main();
